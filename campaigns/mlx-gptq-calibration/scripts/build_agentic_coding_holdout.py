"""Build a reproducible long-context holdout from pinned software repositories.

The repositories are selected from the permissive-license portion of
SWE-bench Science, but this builder does not copy task instructions, verifier
material, trajectories, or answer patches.  It emits only public files from
the repositories at their recorded base commits.
"""

